"""
Система критериев и классов для оценки чувствительности данных.
Соответствует criteria_system_v3.md: 6 критериев со шкалами 4×3×3×4×3×3, 4 класса.

Соглашение об упорядоченности шкал:
    Градация 1   = НАИБОЛЬШАЯ выраженность чувствительности по критерию,
    Градация ω_q = НАИМЕНЬШАЯ выраженность.

Соответственно классы:
    Класс 1 (C₁) = Строго конфиденциально (самый чувствительный),
    Класс 4 (C₄) = Общедоступно.

Доминирование: x доминирует y ⟺ x ≥ y покоординатно (x менее чувствителен)
              ⟹ class(x) ≥ class(y).
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class CriterionGrade:
    code: str           # "К₁₁"
    title: str          # "Высшая степень регулирования"
    description: str
    examples: str


@dataclass(frozen=True)
class Criterion:
    code: str           # "К₁"
    name: str
    short: str          # короткое имя для логов: "regulation"
    grades: tuple

    @property
    def omega(self) -> int:
        return len(self.grades)


